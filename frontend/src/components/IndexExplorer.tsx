import React, { useEffect, useState } from 'react';
import { IndexData } from '../types';
import { Database, Search, FileText } from 'lucide-react';

export const IndexExplorer: React.FC = () => {
  const [data, setData] = useState<IndexData | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [filterTerm, setFilterTerm] = useState('');

  useEffect(() => {
    const fetchIndex = async () => {
      setLoading(true);
      try {
        const res = await fetch('/api/index');
        const json = await res.json();
        if (json.success && json.data) {
          setData(json.data);
        } else {
          throw new Error(json.error || 'Failed to fetch index data');
        }
      } catch (err: any) {
        setError(err.message || 'Error connecting to backend API');
      } finally {
        setLoading(false);
      }
    };

    fetchIndex();
  }, []);

  const entries = data?.entries || [];
  const filteredEntries = entries.filter((e) =>
    e.term.toLowerCase().includes(filterTerm.toLowerCase())
  );

  return (
    <div className="w-full max-w-5xl mx-auto space-y-6 animate-fadeIn">
      {/* Header */}
      <div className="glass-card p-6 rounded-2xl border border-slate-800 flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h2 className="text-2xl font-bold text-slate-100 flex items-center gap-2">
            <Database className="w-7 h-7 text-cyan-400" />
            Inverted Index Explorer
          </h2>
          <p className="text-sm text-slate-400 mt-1">
            Browse the sorted lexicon array generated by the C++ engine. Each entry maps a term to its document posting list.
          </p>
        </div>
        <div className="flex items-center gap-4">
          <div className="bg-slate-900 px-4 py-2 rounded-xl border border-slate-800 text-center">
            <span className="text-xs text-slate-500 font-medium block">Unique Terms</span>
            <span className="text-lg font-bold text-cyan-400 font-mono">{data?.totalTerms || 0}</span>
          </div>
          <div className="bg-slate-900 px-4 py-2 rounded-xl border border-slate-800 text-center">
            <span className="text-xs text-slate-500 font-medium block">Indexed Docs</span>
            <span className="text-lg font-bold text-emerald-400 font-mono">{data?.totalDocuments || 0}</span>
          </div>
        </div>
      </div>

      {error && (
        <div className="p-4 rounded-xl bg-rose-950/50 border border-rose-800 text-rose-300 text-sm">
          {error}
        </div>
      )}

      {/* Filter search bar */}
      <div className="relative">
        <div className="absolute inset-y-0 left-0 pl-4 flex items-center pointer-events-none text-slate-500">
          <Search className="w-5 h-5" />
        </div>
        <input
          type="text"
          value={filterTerm}
          onChange={(e) => setFilterTerm(e.target.value)}
          placeholder="Filter index terms..."
          className="w-full pl-11 pr-4 py-3 bg-slate-900/80 border border-slate-800 rounded-xl text-slate-100 placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-cyan-500 transition-all"
        />
      </div>

      {/* Index table */}
      {loading ? (
        <div className="h-64 glass-card rounded-2xl flex items-center justify-center text-cyan-400">
          <div className="w-6 h-6 border-2 border-cyan-400 border-t-transparent rounded-full animate-spin mr-3" />
          <span>Loading sorted inverted index from C++ memory...</span>
        </div>
      ) : (
        <div className="glass-card rounded-2xl border border-slate-800 overflow-hidden shadow-2xl">
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="bg-slate-900/90 text-slate-400 text-xs uppercase tracking-wider border-b border-slate-800">
                  <th className="py-3.5 px-6 font-semibold"># Index</th>
                  <th className="py-3.5 px-6 font-semibold">Lexicon Term</th>
                  <th className="py-3.5 px-6 font-semibold">Posting List (Documents)</th>
                  <th className="py-3.5 px-6 font-semibold text-right">Frequency</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-800/60 text-sm">
                {filteredEntries.length > 0 ? (
                  filteredEntries.map((entry, idx) => (
                    <tr key={entry.term} className="hover:bg-slate-800/50 transition-colors">
                      <td className="py-3 px-6 text-slate-500 font-mono text-xs">{idx}</td>
                      <td className="py-3 px-6 font-mono font-semibold text-cyan-300 flex items-center gap-2">
                        <span>{entry.term}</span>
                      </td>
                      <td className="py-3 px-6">
                        <div className="flex flex-wrap gap-1.5">
                          {entry.documents.map((doc) => (
                            <span
                              key={doc}
                              className="px-2.5 py-0.5 text-xs bg-slate-800 text-slate-300 rounded-md border border-slate-700 flex items-center gap-1"
                            >
                              <FileText className="w-3 h-3 text-cyan-400" />
                              {doc}
                            </span>
                          ))}
                        </div>
                      </td>
                      <td className="py-3 px-6 text-right font-mono text-xs text-slate-400">
                        {entry.documents.length} doc{entry.documents.length > 1 ? 's' : ''}
                      </td>
                    </tr>
                  ))
                ) : (
                  <tr>
                    <td colSpan={4} className="py-8 text-center text-slate-500 text-sm">
                      No matching terms found in the index.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
};
